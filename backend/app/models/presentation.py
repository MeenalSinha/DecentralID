import uuid
import datetime
from sqlalchemy import String, DateTime, ForeignKey, Text, JSON, Integer
from sqlalchemy.orm import Mapped, mapped_column, relationship
from backend.app.models.base import Base, TimestampMixin

class PresentationShare(Base, TimestampMixin):
    """
    Stores privacy-preserving Verifiable Presentations generated by holders.
    Tokens are opaque high-entropy references used for QR code verification without exposing PII.
    """
    __tablename__ = "presentation_shares"

    id: Mapped[str] = mapped_column(String(36), primary_key=True, default=lambda: str(uuid.uuid4()))
    token: Mapped[str] = mapped_column(String(64), unique=True, index=True, nullable=False)
    holder_address: Mapped[str] = mapped_column(String(42), index=True, nullable=False)
    credential_id: Mapped[str] = mapped_column(String(66), nullable=False, index=True)
    
    # Selective disclosure data
    disclosed_claims: Mapped[dict] = mapped_column(JSON, nullable=False, default=dict)
    presentation_document: Mapped[dict] = mapped_column(JSON, nullable=False)
    
    # Validity and rate limiting
    expires_at: Mapped[datetime.datetime] = mapped_column(DateTime(timezone=True), nullable=False)
    access_count: Mapped[int] = mapped_column(Integer, default=0, nullable=False)
    max_access: Mapped[int] = mapped_column(Integer, default=50, nullable=False)
